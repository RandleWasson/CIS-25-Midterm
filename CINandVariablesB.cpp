#include <iostream>
#include <string>

using namespace std;

int main() {
	// Declare and initialize variables
	int myInt = 10;
	float myFloat = 3.14f;
	char myChar = 'A';
	string myString = "Hello, World!";

	// Print their values
	cout << "Integer value: " << myInt << endl;
	cout << "Float value: " << myFloat << endl;
	cout << "Character value: " << myChar << endl;
	cout << "String value: " << myString << endl;

	return 0;
}